//! # nomos-mesh
//!
//! **Driven port.** The control network between Loom and Cells: node
//! enrollment, node identity, reachability/addressing, and revocation.
//!
//! Lets Cells initiate an authenticated connection to Loom across NAT and
//! firewalls without exposing a management port.
//!
//! Adapters: `nomos-mesh-headscale`.
